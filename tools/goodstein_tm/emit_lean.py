# Emit lean/Collatz/GoodsteinTM/Table.lean from the JSON machines: the seed-independent core table,
# plus, for each given JSON machine, its full (state, symbol) table as a list literal, so Lean can
# check by `decide` that `machine (cells t)` IS that JSON machine.
#   python3 emit_lean.py OUT.lean halt_4.json:4 halt_16.json:16
import json, sys
SYM = {'_': 'blank', 'b': 'b', 'B': 'B', '[': 'lb', ']': 'rb', 'P': 'P', 'd': 'd', 'e': 'e', 'T': 'T',
       'C': 'C', 'D': 'D', 'S': 'S', 'z': 'z', 's': 's', 'p': 'p', 'y': 'y'}
def is_init(s): return s == 'INIT' or (s[0] == 'I' and s[1:].isdigit())
def lst(s): return '.init 0' if s == 'INIT' else '.init %s' % s[1:] if is_init(s) else '.core .%s' % s
out, specs = sys.argv[1], [a.split(':') for a in sys.argv[2:]]
machines = [(json.load(open(p)), int(n)) for p, n in specs]
core = {s: r for s, r in machines[0][0]['table'].items() if not is_init(s)}
for M, _ in machines:
    assert {s: r for s, r in M['table'].items() if not is_init(s)} == core, 'core tables differ'
L = ['/-', 'Copyright (c) 2026 Trevor Morris. All rights reserved.',
     'Released under Apache 2.0 license as described in the file LICENSE.', 'Authors: Trevor Morris', '-/',
     'import Collatz.GoodsteinTM.Machine', '', '/-!', '# The Goodstein machine table (generated)', '',
     'Generated by `tools/goodstein_tm/emit_lean.py` from the JSON machines; do not edit by hand.',
     '`coreTable` is the seed-independent part.  `json<N>` lists every (state, symbol) entry of',
     '`tools/goodstein_tm/halt_<N>.json`, for the faithfulness checks in `Check.lean`.', '-/', '',
     'namespace GoodsteinTM', '', '/-- Tape symbols; `blank` (the default) is `_` in the JSON. -/', 'inductive Sy']
L += ['  | %s' % SYM[c] for c in machines[0][0]['symbols']]
L += ['  deriving DecidableEq, Repr, Inhabited', '', '/-- The seed-independent states. -/', 'inductive Core']
L += ['  | %s' % s for s in core]
L += ['  deriving DecidableEq, Repr, Inhabited', '',
      '/-- States: `init i` writes cell `i` of the seed tape; `core c` is the seed-independent part. -/',
      'inductive St', '  | init (i : ℕ)', '  | core (c : Core)', '  deriving DecidableEq, Repr', '',
      '/-- The seed-independent transitions. -/',
      'def coreTable : Core → Sy → Option (Sy × Dir × St)']
for s, row in core.items():
    for c, (w, m, nx) in row.items():
        L.append('  | .%s, .%s => some (.%s, .%s, %s)' % (s, SYM[c], SYM[w], m, lst(nx)))
L += ['  | _, _ => none', '']
for M, n in machines:
    T = M['table']
    L += ['/-- Every (state, symbol) entry of `halt_%d.json`; `none` = undefined (halt). -/' % n,
          'def json%d : List (St × Sy × Option (Sy × Dir × St)) := [' % n]
    ents = []
    for s in T:
        for c in M['symbols']:
            r = T[s].get(c)
            ents.append('  (%s, .%s, %s)' % (lst(s), SYM[c], 'none' if r is None else
                        'some (.%s, .%s, %s)' % (SYM[r[0]], r[1], lst(r[2]))))
    L += [',\n'.join(ents), ']', '']
L += ['end GoodsteinTM', '']
open(out, 'w').write('\n'.join(L))
print('core states', len(core), 'core transitions', sum(len(r) for r in core.values()))
